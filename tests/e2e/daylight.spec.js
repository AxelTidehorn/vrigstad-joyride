import {test,expect} from '@playwright/test';
import {watchErrors} from './render-helpers.js';
const state=page=>page.evaluate(()=>window.__joyride.state());
test('solar date edits persist and Visual Lab does not move the player',async({page})=>{
 const errors=watchErrors(page);
 await page.goto('/index.html?dev=lighting&time=13&date=2026-06-21');
 await expect.poll(async()=>(await state(page)).daylight.elevation).toBeGreaterThan(54);
 await page.locator('#go').click();
 const date=page.locator('#lab-date');
 await date.focus();await date.press('ArrowRight');await date.press('ArrowUp');
 const editing=await date.inputValue();await page.waitForTimeout(600);
 expect(await date.inputValue()).toBe(editing);
 await date.fill('2026-12-21');await date.press('Tab');
 await expect.poll(async()=>(await state(page)).daylight.elevation).toBeLessThan(10);
 await page.locator('#lab-time').focus();
 const before=await state(page);
 await page.keyboard.down('w');await page.waitForTimeout(300);await page.keyboard.up('w');
 const after=await state(page);
 expect(after.x).toBeCloseTo(before.x,5);expect(after.z).toBeCloseTo(before.z,5);
 expect(errors).toEqual([]);
});
test('cloud and glare controls enable lighting from off and reset accurately',async({page})=>{
 const errors=watchErrors(page);
 await page.goto('/index.html?dev=lighting&lighting=off');await page.locator('#go').click();
 expect((await state(page)).daylight).toMatchObject({enabled:false,cycle:false,coverage:0,glare:1});
 await page.locator('#lab-cloud').focus();await page.keyboard.press('End');
 await expect.poll(async()=>(await state(page)).daylight.coverage).toBe(1);
 expect((await state(page)).daylight.enabled).toBe(true);
 await page.locator('#lab-reset').click();
 expect((await state(page)).daylight.enabled).toBe(false);
 await page.locator('#lab-glare').focus();await page.keyboard.press('Home');
 await expect.poll(async()=>(await state(page)).daylight.glare).toBe(0);
 expect((await state(page)).daylight.enabled).toBe(true);
 await page.locator('#lab-reset').click();
 expect(await page.locator('#lab-glare').inputValue()).toBe('1');
 expect(await page.locator('#lab-cloud').inputValue()).toBe('0');
 expect(errors).toEqual([]);
});
test('night disables sun shadows and day disables the lamp bank',async({page},info)=>{
 const errors=watchErrors(page);
 await page.goto('/index.html?dev=lighting&time=23');await page.locator('#go').click();
 await expect.poll(async()=>(await state(page)).streetlights.active).toBeGreaterThan(0);
 expect((await state(page)).daylight).toMatchObject({sunStrength:0,sunVisible:false,sunCastShadow:false});
 await page.screenshot({path:info.outputPath('night.png')});
 await page.getByRole('button',{name:'13:00',exact:true}).click();
 await expect.poll(async()=>(await state(page)).streetlights.level).toBe(0);
 expect((await state(page)).daylight.sunCastShadow).toBe(true);
 expect(await page.evaluate(()=>document.querySelector('#gl').getContext('webgl2').getError())).toBe(0);
 expect(errors).toEqual([]);
});
